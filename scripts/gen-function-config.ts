// Writes supabase/functions/parking/rules_config.ts from config/rules.json + config/holidays.json.
import { readFile, writeFile } from "node:fs/promises";
const rules = JSON.parse(await readFile("config/rules.json", "utf8"));
const holidays = JSON.parse(await readFile("config/holidays.json", "utf8")).days;
delete rules._sources;
await writeFile(
  "supabase/functions/parking/rules_config.ts",
  `// Generated by scripts/gen-function-config.ts from config/rules.json and config/holidays.json. Do not edit.\nexport default ${JSON.stringify({ ...rules, holidays })};\n`,
);
